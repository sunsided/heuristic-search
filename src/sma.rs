//! Simplified memory-bounded A* (SMA*, Russell 1992): [`sma_star`] and [`sma_star_multi`].
//!
//! SMA* runs A* on the search tree with at most `memory` nodes in memory. When a newly
//! generated child does not fit, the worst leaf (largest backed-up `f`, shallowest first)
//! is forgotten, and its parent remembers the forgotten child's position and backed-up
//! `f`. The smallest such value keeps the parent on the open list, so the best forgotten
//! child is regenerated, with its old value, once it is the most promising part of the
//! tree again. (Each node thus keeps one value per forgotten child; `memory` counts
//! nodes.) Values are backed up like in
//! [`rbfs`](fn@crate::rbfs): a node's `f` is the smallest `f` of its children in memory and of
//! the forgotten ones, never less than before.
//!
//! ```mermaid
//! flowchart TD
//!     pop[pop open node with smallest key, deepest first] -->|key infinite| done[Unsolvable or Cutoff]
//!     pop --> goal{goal?}
//!     goal -->|yes| found[Found]
//!     goal -->|no| generate[first time: all successors; later: best forgotten child]
//!     generate --> prune{over memory?}
//!     prune -->|yes| forget[forget worst leaf into its parent]
//!     forget --> prune
//!     prune -->|no| backup[back up f to the ancestors]
//!     backup --> pop
//! ```

