/// SMA* from `start` with at most `memory` search nodes in memory: A* that forgets its
/// worst leaves when memory runs out and regenerates them when needed.
///
/// A tree search like [`ida_star`](crate::ida_star): states need only `Eq`, and successors
/// already on a node's path are skipped. Successors must be reported in the same order
/// every time, since forgotten children are regenerated by their position.
///
/// `memory` counts nodes in memory between expansions. While a node is expanded for the
/// first time all its successors are created before the worst leaves are forgotten, so the
/// count briefly exceeds `memory` by up to the branching factor; and each node also keeps
/// one value per forgotten child.
///
/// The search returns the cheapest path among those with at most `memory - 1` edges, for
/// an admissible `heuristic` (consistency is not needed; `None` marks a dead end). Longer
/// paths do not fit: each node on a path stays in memory while its subtree is searched,
/// plus one child. So the solution is optimal whenever some optimal path has at most
/// `memory - 1` edges. If memory is too small for any solution, the outcome is
/// [`Outcome::Cutoff`]: a larger `memory` may find one. [`Outcome::Unsolvable`] means no
/// goal is reachable at all (no path was cut off by memory). Goals are tested when a node
/// is taken from the open list. [`Stats::expanded`] counts every expansion, also
/// regenerations of forgotten children.
///
/// # Examples
///
/// ```
/// use heuristic_search::{Limits, Outcome, Successors, Zero, sma_star};
///
/// /// `0 -> 3` directly costs 10; `0 -> 1 -> 2 -> 3` costs 3.
/// struct Shortcut;
///
/// impl Successors for Shortcut {
///     type State = u8;
///     type Action = ();
///     type Cost = u32;
///
///     fn successors(&self, n: &u8, mut emit: impl FnMut((), u8, u32)) {
///         match n {
///             0 => {
///                 emit((), 3, 10);
///                 emit((), 1, 1);
///             }
///             1 => emit((), 2, 1),
///             2 => emit((), 3, 1),
///             _ => {}
///         }
///     }
/// }
///
/// let is_three = |n: &u8| *n == 3;
/// let roomy = sma_star(&Shortcut, 0, &is_three, Zero, 4, Limits::NONE);
/// let tight = sma_star(&Shortcut, 0, &is_three, Zero, 2, Limits::NONE);
/// let tiny = sma_star(&Shortcut, 0, &is_three, Zero, 1, Limits::NONE);
///
/// assert_eq!(roomy.solution().map(|s| s.cost), Some(3));
/// // Two nodes hold paths of one edge only.
/// assert_eq!(tight.solution().map(|s| s.cost), Some(10));
/// assert_eq!(tiny.outcome, Outcome::Cutoff);
/// ```
pub fn sma_star<G, T, H>(
    graph: &G,
    start: G::State,
    goal: &T,
    heuristic: H,
    memory: usize,
    budget: impl Budget<Stats>,
) -> GraphResult<G>
where
    G: Successors,
    G::State: Clone + Eq,
    G::Action: Clone,
    T: Goal<G::State> + ?Sized,
    H: Heuristic<G::State, G::Cost>,
{
    sma_star_multi(graph, [start], goal, heuristic, memory, budget)
}

/// [`sma_star`] from several start states at once.
///
/// Every distinct start stays in memory and counts against `memory`, so with `k` starts
/// the paths that fit have at most `memory - k` edges; with more starts than `memory` the
/// outcome is [`Outcome::Cutoff`]. Repeated starts count once, an empty set of starts is
/// [`Outcome::Unsolvable`], and a start that is a goal is returned as a zero-cost path.
///
/// # Examples
///
/// ```
/// use heuristic_search::{Limits, Successors, heuristic_fn, sma_star_multi};
///
/// /// Counting up by one, at cost 1.
/// struct Up;
///
/// impl Successors for Up {
///     type State = u32;
///     type Action = ();
///     type Cost = u32;
///
///     fn successors(&self, n: &u32, mut emit: impl FnMut((), u32, u32)) {
///         if *n < 8 {
///             emit((), n + 1, 1);
///         }
///     }
/// }
///
/// let h = heuristic_fn(|n: &u32| 8_u32.checked_sub(*n));
/// let result = sma_star_multi(&Up, [0, 6, 3], &|n: &u32| *n == 8, h, 6, Limits::NONE);
///
/// assert_eq!(result.solution().map(|s| s.states.clone()), Some(vec![6, 7, 8]));
/// ```
pub fn sma_star_multi<G, T, H>(
    graph: &G,
    starts: impl IntoIterator<Item = G::State>,
    goal: &T,
    heuristic: H,
    memory: usize,
    budget: impl Budget<Stats>,
) -> GraphResult<G>
where
    G: Successors,
    G::State: Clone + Eq,
    G::Action: Clone,
    T: Goal<G::State> + ?Sized,
    H: Heuristic<G::State, G::Cost>,
{
    let roots = distinct(starts);
    if let Some(solution) = goal_root(&roots, goal) {
        return SearchResult {
            outcome: Outcome::Found(solution),
            stats: Stats::default(),
        };
    }

    let mut search = Sma {
        graph,
        goal,
        heuristic,
        memory,
        roots: roots.len(),
        nodes: Vec::new(),
        free: Vec::new(),
        open: KeyedSet::new(),
        leaves: KeyedSet::new(),
        live: 0,
        created: 0,
        cut: false,
        stats: Stats::default(),
    };
    let outcome = if roots.len() > memory {
        Outcome::Cutoff
    } else {
        search.run(roots, budget)
    };

    SearchResult {
        outcome,
        stats: search.stats,
    }
}

/// A node of the search tree in memory.
struct Node<S, A, C> {
    /// The state.
    state: S,
    /// The edge label and cost from the parent; `None` for a start.
    via: Option<(A, C)>,
    /// The parent's slot; `None` for a start.
    parent: Option<usize>,
    /// The position of this node among its parent's successors, as the graph reports them.
    edge: usize,
    /// The number of edges from the start.
    depth: usize,
    /// The path cost from the start.
    g: C,
    /// The backed-up value `F`: a lower bound on the cost of any solution below this node.
    value: Extended<C>,
    /// The slots of the children in memory.
    children: Vec<usize>,
    /// The position and backed-up value of every forgotten child, so a regenerated child
    /// gets its value back.
    forgotten: Vec<(usize, Extended<C>)>,
    /// Whether the node has been expanded, so its children were generated once.
    expanded: bool,
    /// Creation counter, for deterministic tie-breaking.
    seq: u64,
}

/// A node over graph `G`.
type GraphNode<G> =
    Node<<G as Successors>::State, <G as Successors>::Action, <G as Successors>::Cost>;

/// Open-list key: smallest value first, then deepest, then oldest.
type OpenKey<C> = (Extended<C>, Reverse<usize>, u64);

/// Pruning key: largest value first, then shallowest, then oldest (so a child that was
/// just regenerated is not the first to go among equals).
type LeafKey<C> = (Reverse<Extended<C>>, usize, u64);

/// One SMA* run.
struct Sma<'a, G: Successors, T: ?Sized, H> {
    /// The graph being searched.
    graph: &'a G,
    /// The goal test.
    goal: &'a T,
    /// The heuristic, owned for the run.
    heuristic: H,
    /// The most nodes in memory at once.
    memory: usize,
    /// The number of distinct starts, which never leave memory.
    roots: usize,
    /// Node slots; `None` for free slots.
    nodes: Vec<Option<GraphNode<G>>>,
    /// Free slots for reuse.
    free: Vec<usize>,
    /// Nodes that can be expanded: leaves, and nodes with forgotten children.
    open: KeyedSet<OpenKey<G::Cost>>,
    /// Leaves that may be forgotten (every leaf except the starts).
    leaves: KeyedSet<LeafKey<G::Cost>>,
    /// The number of nodes in memory.
    live: usize,
    /// Nodes created so far.
    created: u64,
    /// Whether memory has cut off a path, so a goal may lie beyond it.
    cut: bool,
    /// Counters for the result.
    stats: Stats,
}

impl<G, T, H> Sma<'_, G, T, H>
where
    G: Successors,
    G::State: Clone + Eq,
    G::Action: Clone,
    T: Goal<G::State> + ?Sized,
    H: Heuristic<G::State, G::Cost>,
{
    /// Searches from `roots`, none of which is a goal and no more than `memory` of them.
    ///
    /// Values are backed up before pruning: forgetting a leaf moves its value into the
    /// parent's forgotten value, which leaves every backed-up value as it was.
    fn run(
        &mut self,
        roots: Vec<G::State>,
        mut budget: impl Budget<Stats>,
    ) -> Outcome<G::State, G::Action, G::Cost> {
        for (edge, state) in roots.into_iter().enumerate() {
            let value = Extended::f(G::Cost::ZERO, self.heuristic.estimate(&state));
            let id = self.create(Node {
                state,
                via: None,
                parent: None,
                edge,
                depth: 0,
                g: G::Cost::ZERO,
                value,
                children: Vec::new(),
                forgotten: Vec::new(),
                expanded: false,
                seq: 0,
            });
            self.refresh(id);
        }

        loop {
            let Some((&(key, _, _), id)) = self.open.first() else {
                return self.exhausted();
            };

            if key == Extended::Infinite {
                return self.exhausted();
            }

            if self.goal.is_goal(&self.node(id).state) {
                return Outcome::Found(self.solution(id));
            }

            if budget.exhausted(&self.stats) {
                return Outcome::LimitReached;
            }

            self.generate(id, key);
            self.back_up(id);
            self.prune();
        }
    }

    /// The outcome once nothing below infinity is left to expand.
    fn exhausted(&self) -> Outcome<G::State, G::Action, G::Cost> {
        if self.cut {
            Outcome::Cutoff
        } else {
            Outcome::Unsolvable
        }
    }

    /// Expands `id`: generates all its successors on the first expansion, each valued at
    /// least `bound` (the key `id` was taken with), and later regenerates only its
    /// forgotten child with the smallest remembered value, which it gets back.
    fn generate(&mut self, id: usize, bound: Extended<G::Cost>) {
        let mut edges = Vec::new();
        self.stats.expanded += 1;
        self.stats.generated += collect_successors(self.graph, &self.node(id).state, &mut edges);

        let node = self.node_mut(id);
        let wanted = if node.expanded {
            let best = (0..node.forgotten.len())
                .min_by_key(|&index| node.forgotten[index].1)
                .expect("an expanded node is open only with forgotten children");

            Some(node.forgotten.swap_remove(best))
        } else {
            node.expanded = true;
            None
        };

        for (edge, (action, state, cost)) in edges.into_iter().enumerate() {
            let value = match wanted {
                Some((forgotten, value)) if forgotten == edge => value,
                Some(_) => continue,
                None => bound,
            };

            self.add_child(id, edge, action, state, cost, value);
        }

        self.refresh(id);
    }

    /// Adds the successor `state` at position `edge` of `id` as a child valued at least
    /// `bound`, unless it is on the path, a dead end, or does not fit in memory.
    fn add_child(
        &mut self,
        id: usize,
        edge: usize,
        action: G::Action,
        state: G::State,
        cost: G::Cost,
        bound: Extended<G::Cost>,
    ) {
        if self.on_path(id, &state) {
            return;
        }

        // The child must fit next to its path and the other starts, and a non-goal child
        // also needs room for a child of its own.
        let (g, depth) = (self.node(id).g + cost, self.node(id).depth + 1);
        let needed = self.roots + depth;
        if needed > self.memory || (needed == self.memory && !self.goal.is_goal(&state)) {
            self.cut = true;
            return;
        }

        let Some(h) = self.heuristic.estimate(&state) else {
            return;
        };

        let child = self.create(Node {
            state,
            via: Some((action, cost)),
            parent: Some(id),
            edge,
            depth,
            g,
            value: bound.max(Extended::Finite(g.saturating_add(h))),
            children: Vec::new(),
            forgotten: Vec::new(),
            expanded: false,
            seq: 0,
        });
        self.node_mut(id).children.push(child);
        self.refresh(child);
    }

    /// Forgets the worst leaves until the nodes fit in memory.
    fn prune(&mut self) {
        while self.live > self.memory {
            let (_, leaf) = self
                .leaves
                .first()
                .expect("only starts are not prunable, and they fit");
            self.forget(leaf);
        }
    }

    /// Removes the leaf `id`; its parent remembers its value.
    fn forget(&mut self, id: usize) {
        self.open.remove(id);
        self.leaves.remove(id);
        let node = self.nodes[id].take().expect("a live node");
        self.free.push(id);
        self.live -= 1;

        let parent = node.parent.expect("starts are never forgotten");
        let entry = self.node_mut(parent);
        entry.children.retain(|&child| child != id);
        entry.forgotten.push((node.edge, node.value));
        self.refresh(parent);
    }

    /// Recomputes the value of `id` from its children and forgotten children, and those of
    /// its ancestors while they change.
    fn back_up(&mut self, mut id: usize) {
        loop {
            let node = self.node(id);
            let best = node
                .children
                .iter()
                .map(|&child| self.node(child).value)
                .fold(smallest_forgotten(node), Extended::min);
            let value = node.value.max(best);
            if value == node.value {
                return;
            }

            self.node_mut(id).value = value;
            self.refresh(id);
            match self.node(id).parent {
                Some(parent) => id = parent,
                None => return,
            }
        }
    }

    /// Puts `id` into the open list and the leaf set as its children and values say.
    fn refresh(&mut self, id: usize) {
        let node = self.node(id);
        let leaf = node.children.is_empty();
        let key = if leaf {
            Some(node.value)
        } else {
            Some(smallest_forgotten(node)).filter(|&f| f != Extended::Infinite)
        };
        let (depth, seq, value, prunable) = (
            node.depth,
            node.seq,
            node.value,
            leaf && node.parent.is_some(),
        );

        match key {
            Some(key) => self.open.insert(id, (key, Reverse(depth), seq)),
            None => {
                self.open.remove(id);
            }
        }

        if prunable {
            self.leaves.insert(id, (Reverse(value), depth, seq));
        } else {
            self.leaves.remove(id);
        }
    }

    /// Returns `true` if `state` is the state of `id` or of one of its ancestors.
    fn on_path(&self, mut id: usize, state: &G::State) -> bool {
        loop {
            let node = self.node(id);
            if node.state == *state {
                return true;
            }

            match node.parent {
                Some(parent) => id = parent,
                None => return false,
            }
        }
    }

    /// Stores `node` in a free slot and returns the slot.
    fn create(&mut self, mut node: Node<G::State, G::Action, G::Cost>) -> usize {
        node.seq = self.created;
        self.created += 1;
        self.live += 1;
        if let Some(id) = self.free.pop() {
            self.nodes[id] = Some(node);
            return id;
        }

        self.nodes.push(Some(node));

        self.nodes.len() - 1
    }

    /// The path from a start to `id`.
    fn solution(&self, id: usize) -> Solution<G::State, G::Action, G::Cost> {
        let mut states = Vec::new();
        let mut actions = Vec::new();
        let mut cost = G::Cost::ZERO;
        let mut at = Some(id);
        while let Some(current) = at {
            let node = self.node(current);
            states.push(node.state.clone());
            if let Some((action, edge_cost)) = &node.via {
                actions.push(action.clone());
                cost = cost + *edge_cost;
            }

            at = node.parent;
        }

        states.reverse();
        actions.reverse();

        Solution {
            states,
            actions,
            cost,
        }
    }

    /// The live node in slot `id`.
    fn node(&self, id: usize) -> &Node<G::State, G::Action, G::Cost> {
        self.nodes[id].as_ref().expect("a live node")
    }

    /// The live node in slot `id`, mutably.
    fn node_mut(&mut self, id: usize) -> &mut Node<G::State, G::Action, G::Cost> {
        self.nodes[id].as_mut().expect("a live node")
    }
}

/// The smallest value among the forgotten children of `node`; infinite if there are none.
fn smallest_forgotten<S, A, C: Cost>(node: &Node<S, A, C>) -> Extended<C> {
    node.forgotten
        .iter()
        .map(|&(_, value)| value)
        .min()
        .unwrap_or(Extended::Infinite)
}
